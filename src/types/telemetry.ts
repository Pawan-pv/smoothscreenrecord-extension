export interface BoundingBox {
  x: number;
  y: number;
  width: number;
  height: number;
}

export interface MousePoint {
  t: number; // relative timestamp in ms from recording start
  x: number; // normalised or pixel x coordinate
  y: number; // normalised or pixel y coordinate
  c: string; // cursor style: 'default' | 'pointer' | 'text' | 'grab' etc.
}

export interface ClickEvent {
  t: number;
  x: number;
  y: number;
  button: number;
  targetTag: string;
  targetText?: string;
  containerBounds?: BoundingBox;
}

export interface KeystrokeEvent {
  t: number;
  key: string;
  combo: string; // e.g. "⌘K", "Ctrl+C", "Enter"
}

export interface InputFocusEvent {
  t: number;
  type: 'focus' | 'blur' | 'type';
  bounds: BoundingBox;
}

export interface RecordingMetadata {
  id: string;
  startTime: number;
  endTime: number;
  durationMs: number;
  width: number;
  height: number;
  devicePixelRatio: number;
  title: string;
  url?: string;
  brandColors?: {
    primary: string;
    secondary: string;
    accent: string;
    background: string;
  };
}

export interface CaptionWord {
  word: string;
  startTime: number;
  endTime: number;
}

export interface CaptionBlock {
  id: string;
  startTime: number;
  endTime: number;
  text: string;
  words: CaptionWord[];
}

export type CaptionStyle = 'tiktok-bold' | 'apple-keynote' | 'minimal-pill' | 'classic-sub';

export type CursorTheme = 'mac-obsidian' | 'neon-glow' | 'minimal-white';

export interface TelemetryData {
  metadata: RecordingMetadata;
  mousePoints: MousePoint[];
  clicks: ClickEvent[];
  keystrokes: KeystrokeEvent[];
  inputEvents: InputFocusEvent[];
  captions?: CaptionBlock[];
}

export interface ZoomPill {
  id: string;
  startTime: number;
  endTime: number;
  targetX: number; // 0..1 normalised screen coordinates
  targetY: number; // 0..1 normalised screen coordinates
  targetScale: number; // e.g. 1.2 to 2.8
  tiltX: number; // isometric degrees
  tiltY: number; // isometric degrees
  spotlight: boolean; // spotlight dimming mask toggle
  label?: string;
  autoGenerated?: boolean;
}

export interface SilenceSegment {
  id: string;
  startTime: number;
  endTime: number;
  duration: number;
  markedForCut: boolean;
}

export type AspectRatioType = '16:9' | '9:16' | '1:1' | '4:3';

export type VibePresetId = 'linear-dark' | 'apple-keynote' | 'stripe-mesh' | 'indie-pop' | 'minimal-clean' | 'custom';

export interface VibePreset {
  id: VibePresetId;
  name: string;
  gradientColors: [string, string, string];
  borderRadius: number;
  shadowBlur: number;
  shadowColor: string;
  cursorRingColor: string;
  keycapTheme: 'dark' | 'light' | 'glass';
}
